            const holdButton = document.getElementById('holdButton');
            ['pointerdown', 'touchstart'].forEach((eventName) => holdButton.addEventListener(eventName, startMeter));
            ['pointerup', 'pointerleave', 'pointercancel', 'touchend'].forEach((eventName) => holdButton.addEventListener(eventName, stopMeter));
        }

        function startMeter(event) {
            event.preventDefault();
            if (state.meterTimer || state.meter >= 100) return;
            state.meterTimer = setInterval(() => {
                state.meter = Math.min(100, state.meter + 2);
                const meterValue = document.getElementById('meterValue');
                const meterFill = document.getElementById('meterFill');
                const meterCopy = document.getElementById('meterMessage');
                if (meterValue) meterValue.textContent = `${state.meter}%`;
                if (meterFill) meterFill.style.width = `${state.meter}%`;
                if (meterCopy) meterCopy.textContent = meterMessage();
                if (state.meter >= 100) {
                    stopMeter();
                    setTimeout(() => showCompletion('letter', 'Love Meter Penuh! Kamu Berhasil Menyelesaikan Semua Chapter & Hadiah Utama Sekarang Sudah Bisa Dibuka.'), 340);
                }
            }, 55);
        }

        function stopMeter() {
            if (!state.meterTimer) return;
            clearInterval(state.meterTimer);
            state.meterTimer = null;
        }

        function renderLetter() {
            if (!state.letterOpened) {
                stageRoot.innerHTML = chapterShell({
                    eyebrow: 'Final Chapter · The Letter',
                    title: 'Satu Surat Terakhir Menunggumu',
                    description: 'Gamenya Selesai! Sekarang Bagian Yang Paling Penting...Buka Saat Kamu Sudah Siap!',
                    content: `
                        <button id="openLetterButton" class="letter-envelope" type="button">
                            <span class="envelope-symbol">✉</span>
                            <span>Open your letter</span>
                        </button>
                    `
                });
                document.getElementById('openLetterButton').addEventListener('click', () => {
                    state.letterOpened = true;
                    renderLetter();
                });
                return;
            }

            const page = CONFIG.letterPages[state.letterPage];
            const dots = CONFIG.letterPages.map((_, index) => `<span class="letter-dot ${index === state.letterPage ? 'active' : ''}"></span>`).join('');
            const action = state.letterPage < CONFIG.letterPages.length - 1
                ? `<button id="nextLetterButton" class="text-button" type="button">Halaman Berikutnya <span>›</span></button>`
                : `<span class="quest-complete">★ Quest completed</span>`;

            stageRoot.innerHTML = chapterShell({
                eyebrow: `A letter from ${CONFIG.senderName}`,
                title: page.title,
                content: `
                    <div class="glass-card letter-card">
                        <p class="letter-body">${escapeHtml(page.body)}</p>
                        <div class="letter-footer">
                            <div class="letter-dots">${dots}</div>
                            ${action}
                        </div>
                    </div>
                    ${state.letterPage === CONFIG.letterPages.length - 1 ? `<p class="signature">With Love, ${escapeHtml(CONFIG.senderName)} ♡</p>` : ''}
                `
            });

            const nextButton = document.getElementById('nextLetterButton');
            if (nextButton) {
                nextButton.addEventListener('click', () => {
                    state.letterPage += 1;
                    renderLetter();
                });
            }
        }

        function renderStage() {
            stopMeter();
            updateProgress();
            if (state.stage === 'cover') renderCover();
            if (state.stage === 'hearts') renderHearts();
            if (state.stage === 'memory') renderMemory();
            if (state.stage === 'quiz') renderQuiz();
            if (state.stage === 'meter') renderMeter();
            if (state.stage === 'letter') renderLetter();
        }

        function renderQuoteModal() {
            modalRoot.innerHTML = `
                <div class="modal-backdrop" id="quoteBackdrop">
                    <div class="quote-modal modal-enter">
                        <div class="quote-header">
                            ${pill('Words for you')}
                            <button id="closeQuoteButton" class="text-button" type="button">Close</button>
                        </div>
                        <p class="quote-copy">“${escapeHtml(CONFIG.quotes[state.quoteIndex])}”</p>
                        <div class="quote-footer">
                            <span>${state.quoteIndex + 1} / ${CONFIG.quotes.length}</span>
                            <button id="nextQuoteButton" class="text-button" type="button">Quote Berikutnya <span>›</span></button>
                        </div>
                    </div>
                </div>
            `;

            document.getElementById('closeQuoteButton').addEventListener('click', closeModal);
            document.getElementById('quoteBackdrop').addEventListener('click', (event) => {
                if (event.target.id === 'quoteBackdrop') closeModal();
            });
            document.getElementById('nextQuoteButton').addEventListener('click', () => {
                state.quoteIndex = (state.quoteIndex + 1) % CONFIG.quotes.length;
                renderQuoteModal();
            });
        }

        function closeModal() {
            modalRoot.innerHTML = '';
        }

        async function playMusic() {
            try {
                await backgroundMusic.play();
                state.musicOn = true;
                musicButton.textContent = '♫';
                musicButton.setAttribute('aria-label', 'Matikan Musik');
            } catch (error) {
                state.musicOn = false;
                musicButton.textContent = '♪';
                console.info('Tambahkan File Song.Mp3 Dan Mulai Musik Melalui Interaksi Pengguna.', error);
            }
        }

        function pauseMusic() {
            backgroundMusic.pause();
            state.musicOn = false;
            musicButton.textContent = '♪';
            musicButton.setAttribute('aria-label', 'Nyalakan Musik');
        }

        function resetGame() {
            stopMeter();
            localStorage.removeItem(STORAGE_KEY);
            Object.assign(state, {
                stage: 'cover',
                caughtHearts: [],
                memoryCards: [],
                selectedCards: [],
                matchedCards: [],
                cardLocked: false,
                quizIndex: 0,
                quizChoice: null,
                meter: 0,
                meterTimer: null,
                letterOpened: false,
                letterPage: 0,
                quoteIndex: 0
            });
            closeModal();
            renderStage();
        }

        function renderFloatingDecor() {
            const decorRoot = document.getElementById('floatingDecor');
            const symbols = ['♥', '✦', '·', '♡'];
            decorRoot.innerHTML = Array.from({ length: 30 }, (_, index) => {
                const left = (index * 43) % 100;
                const top = (index * 67) % 100;
                const delay = (index % 9) * 0.7;
                const duration = 7 + (index % 6);
                const size = 10 + (index % 5) * 3;
                return `<span style="left:${left}%;top:${top}%;animation-delay:${delay}s;animation-duration:${duration}s;font-size:${size}px">${symbols[index % symbols.length]}</span>`;
            }).join('');
        }

        document.getElementById('quoteButton').addEventListener('click', renderQuoteModal);
        musicButton.addEventListener('click', () => state.musicOn ? pauseMusic() : playMusic());
        document.getElementById('resetButton').addEventListener('click', resetGame);

        renderFloatingDecor();
        renderStage();
    </script>
